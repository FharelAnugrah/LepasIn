BEGIN;

-- ---------- 0. RESET ----------
DROP TABLE IF EXISTS chats          CASCADE;
DROP TABLE IF EXISTS wishlists      CASCADE;
DROP TABLE IF EXISTS reviews        CASCADE;
DROP TABLE IF EXISTS order_items    CASCADE;
DROP TABLE IF EXISTS orders         CASCADE;
DROP TABLE IF EXISTS addresses      CASCADE;
DROP TABLE IF EXISTS cart_items     CASCADE;
DROP TABLE IF EXISTS product_images CASCADE;
DROP TABLE IF EXISTS products       CASCADE;
DROP TABLE IF EXISTS categories     CASCADE;
DROP TABLE IF EXISTS stores         CASCADE;
DROP TABLE IF EXISTS users          CASCADE;
DROP TABLE IF EXISTS campuses       CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;

-- ---------- 1. FUNGSI UTILITAS ----------
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- 2. CAMPUSES (Daftar Perguruan Tinggi di Indonesia) ----------
CREATE TABLE campuses (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(150) NOT NULL UNIQUE,   -- mis. "Universitas Hasanuddin"
  short_name VARCHAR(30)  NOT NULL,          -- mis. "UNHAS"
  city       VARCHAR(100) NOT NULL,          -- mis. "Makassar"
  province   VARCHAR(100) NOT NULL,          -- mis. "Sulawesi Selatan"
  created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX campuses_short_name_idx ON campuses (short_name);
CREATE INDEX campuses_city_idx       ON campuses (city);

-- ---------- 3. USERS ----------
CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id     INT          REFERENCES campuses(id) ON DELETE RESTRICT,
  name          VARCHAR(100) NOT NULL,
  email         VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(10)  NOT NULL CHECK (role IN ('admin', 'seller', 'buyer')),
  seller_status VARCHAR(10)  CHECK (seller_status IN ('pending', 'approved', 'rejected')),
  was_approved  BOOLEAN      NOT NULL DEFAULT FALSE,
  id_card_url   TEXT,
  phone         VARCHAR(20),
  avatar_url    TEXT,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CONSTRAINT users_seller_status_chk CHECK (
    (role = 'seller' AND seller_status IS NOT NULL AND campus_id IS NOT NULL) OR
    (role <> 'seller' AND seller_status IS NULL)
  )
);
CREATE UNIQUE INDEX users_email_uq ON users (LOWER(email));
CREATE INDEX users_role_status_idx ON users (role, seller_status);
CREATE INDEX users_campus_idx      ON users (campus_id);

-- ---------- 4. STORES (1 seller = 1 toko, terikat ke 1 kampus) ----------
CREATE TABLE stores (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INT          NOT NULL UNIQUE REFERENCES users(id)    ON DELETE CASCADE,
  campus_id   INT          NOT NULL        REFERENCES campuses(id) ON DELETE RESTRICT,
  name        VARCHAR(100) NOT NULL,
  description TEXT         NOT NULL DEFAULT '',
  image_url   TEXT,
  location    VARCHAR(150),            -- area kost sekitar kampus, mis. "Tamalanrea, Pintu 1"
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX stores_campus_idx ON stores (campus_id);

-- ---------- 5. CATEGORIES (dikelola Admin) ----------
CREATE TABLE categories (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(60) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------- 6. PRODUCTS ----------
CREATE TABLE products (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id       INT          NOT NULL REFERENCES stores(id)     ON DELETE CASCADE,
  category_id    INT          NOT NULL REFERENCES categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  name           VARCHAR(150) NOT NULL,
  description    TEXT         NOT NULL,
  price          INT          NOT NULL CHECK (price > 0),
  original_price INT          CHECK (original_price IS NULL OR original_price > 0),
  stock          INT          NOT NULL DEFAULT 1 CHECK (stock >= 0),
  condition      VARCHAR(15)  NOT NULL CHECK (condition IN ('like_new', 'good', 'fair', 'minor_defect')),
  is_deleted     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX products_store_idx      ON products (store_id);
CREATE INDEX products_category_idx   ON products (category_id);
CREATE INDEX products_price_idx      ON products (price);
CREATE INDEX products_created_idx    ON products (created_at DESC);
CREATE INDEX products_is_deleted_idx ON products (is_deleted);

-- ---------- 7. PRODUCT_IMAGES ----------
CREATE TABLE product_images (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INT         NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url        TEXT        NOT NULL,
  position   SMALLINT    NOT NULL DEFAULT 0 CHECK (position >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX product_images_product_idx ON product_images (product_id, position);

-- ---------- 8. CART_ITEMS ----------
CREATE TABLE cart_items (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT         NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
  product_id INT         NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  quantity   INT         NOT NULL DEFAULT 1 CHECK (quantity > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, product_id)
);

-- ---------- 9. ADDRESSES ----------
CREATE TABLE addresses (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label          VARCHAR(50)  NOT NULL,
  recipient_name VARCHAR(100) NOT NULL,
  phone          VARCHAR(20)  NOT NULL,
  address_line   TEXT         NOT NULL,
  city           VARCHAR(100) NOT NULL,
  postal_code    VARCHAR(10),
  is_default     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX addresses_user_idx ON addresses (user_id);
CREATE UNIQUE INDEX addresses_one_default_uq ON addresses (user_id) WHERE is_default;

-- ---------- 10. ORDERS ----------
CREATE TABLE orders (
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code         VARCHAR(30)  NOT NULL UNIQUE,
  buyer_id           INT          REFERENCES users(id)  ON DELETE SET NULL,
  store_id           INT          REFERENCES stores(id) ON DELETE SET NULL,
  buyer_name         VARCHAR(100) NOT NULL,
  store_name         VARCHAR(100) NOT NULL,
  status             VARCHAR(20)  NOT NULL DEFAULT 'pending_payment'
                     CHECK (status IN ('pending_payment', 'processing', 'shipped', 'completed', 'cancelled')),
  delivery_method    VARCHAR(10)  NOT NULL CHECK (delivery_method IN ('meetup', 'delivery')),
  shipping_recipient VARCHAR(100),
  shipping_phone     VARCHAR(20),
  shipping_address   TEXT,
  note               TEXT,
  total_amount       INT          NOT NULL CHECK (total_amount >= 0),
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CONSTRAINT orders_delivery_chk CHECK (
    delivery_method = 'meetup' OR
    (shipping_recipient IS NOT NULL AND shipping_phone IS NOT NULL AND shipping_address IS NOT NULL)
  )
);
CREATE INDEX orders_buyer_idx ON orders (buyer_id, created_at DESC);
CREATE INDEX orders_store_idx ON orders (store_id, status, created_at DESC);

-- ---------- 11. ORDER_ITEMS ----------
CREATE TABLE order_items (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          INT          NOT NULL REFERENCES orders(id)   ON DELETE CASCADE,
  product_id        INT          REFERENCES products(id)          ON DELETE SET NULL,
  product_name      VARCHAR(150) NOT NULL,
  product_image_url TEXT,
  unit_price        INT          NOT NULL CHECK (unit_price > 0),
  quantity          INT          NOT NULL CHECK (quantity > 0),
  subtotal          INT GENERATED ALWAYS AS (unit_price * quantity) STORED
);
CREATE INDEX order_items_order_idx   ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

-- ---------- 12. REVIEWS ----------
CREATE TABLE reviews (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id INT         NOT NULL UNIQUE REFERENCES order_items(id) ON DELETE CASCADE,
  product_id    INT         NOT NULL REFERENCES products(id)           ON DELETE CASCADE,
  buyer_id      INT         NOT NULL REFERENCES users(id)              ON DELETE CASCADE,
  rating        SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment       TEXT        NOT NULL DEFAULT '',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX reviews_product_idx ON reviews (product_id, created_at DESC);

-- ---------- 13. WISHLISTS ----------
CREATE TABLE wishlists (
  user_id    INT         NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
  product_id INT         NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, product_id)
);

-- ---------- 14. CHATS (Percakapan langsung Seller & Buyer: Pesanan & Tanya Produk) ----------
CREATE TABLE chats (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INT         REFERENCES orders(id)   ON DELETE CASCADE,
  store_id    INT         REFERENCES stores(id)   ON DELETE CASCADE,
  product_id  INT         REFERENCES products(id) ON DELETE SET NULL,
  sender_id   INT         NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
  receiver_id INT         NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
  message     TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX chats_order_idx    ON chats (order_id, created_at ASC);
CREATE INDEX chats_store_idx    ON chats (store_id);
CREATE INDEX chats_product_idx  ON chats (product_id);
CREATE INDEX chats_sender_idx   ON chats (sender_id);
CREATE INDEX chats_receiver_idx ON chats (receiver_id);

-- ---------- 15. TRIGGER updated_at ----------
CREATE TRIGGER users_updated_at    BEFORE UPDATE ON users    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER stores_updated_at   BEFORE UPDATE ON stores   FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER products_updated_at BEFORE UPDATE ON products FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER orders_updated_at   BEFORE UPDATE ON orders   FOR EACH ROW EXECUTE FUNCTION set_updated_at();

